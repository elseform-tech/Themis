#!/usr/bin/env node
// Pins the browser's built-in engine (chrome-headless-shell, Chrome for Testing) to the
// current stable version: downloads every platform's archive once, hashes it, and writes
// crates/core/src/browser/engine_pin.rs. The app downloads only that version and refuses
// an archive whose SHA-256 differs (crates/core/src/browser/engine.rs).
//
// Usage: node scripts/pin-browser-engine.mjs [VERSION]
// Bump deliberately, then run the browser tests and the live check.

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const VERSIONS = "https://googlechromelabs.github.io/chrome-for-testing/known-good-versions-with-downloads.json";
const STABLE = "https://googlechromelabs.github.io/chrome-for-testing/last-known-good-versions.json";
const PREFIX = "https://storage.googleapis.com/chrome-for-testing-public/";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "crates", "core", "src", "browser", "engine_pin.rs");

async function json(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  return response.json();
}

const version = process.argv[2] ?? (await json(STABLE)).channels.Stable.version;
const entry = (await json(VERSIONS)).versions.find(candidate => candidate.version === version);
const downloads = entry?.downloads?.["chrome-headless-shell"];
if (!downloads?.length) throw new Error(`no chrome-headless-shell downloads for ${version}`);

const archives = [];
for (const { platform, url } of downloads) {
  if (url !== `${PREFIX}${version}/${platform}/chrome-headless-shell-${platform}.zip`) {
    throw new Error(`unexpected address for ${platform}: ${url}`);
  }
  const response = await fetch(url, { redirect: "error" });
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  const hash = createHash("sha256");
  for await (const chunk of response.body) hash.update(chunk);
  const sha256 = hash.digest("hex");
  console.log(`${platform} ${sha256}`);
  archives.push([platform, sha256]);
}
archives.sort(([a], [b]) => a.localeCompare(b));

writeFileSync(out, `// Generated by scripts/pin-browser-engine.mjs; bump the engine with that script.

/// The pinned Chrome for Testing version of the built-in engine.
pub const VERSION: &str = "${version}";

/// SHA-256 of each platform's chrome-headless-shell archive for [\`VERSION\`].
pub const ARCHIVES: &[(&str, &str)] = &[
${archives.map(([platform, sha256]) => `    ("${platform}", "${sha256}"),`).join("\n")}
];
`);
console.log(`pinned chrome-headless-shell ${version} in ${out}`);
